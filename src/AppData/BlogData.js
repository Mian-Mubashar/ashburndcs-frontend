export const getBlogBySlug = (slug) => {
  if (!slug) return null;
  const clean = String(slug).trim().toLowerCase();
  return BLOGS_DATA.find((item) => item.slug.toLowerCase() === clean) || null;
};

export const getRelatedBlogs = (currentSlug, limit = 3) => {
  const current = getBlogBySlug(currentSlug);
  if (!current) return BLOGS_DATA.slice(0, limit);
  return BLOGS_DATA
    .filter((b) => b.slug !== current.slug)
    .sort((a, b) => {
      // Prioritize same category or same city tag
      let scoreA = 0;
      let scoreB = 0;
      if (a.category === current.category) scoreA += 2;
      if (a.cityTag === current.cityTag) scoreA += 1;
      if (b.category === current.category) scoreB += 2;
      if (b.cityTag === current.cityTag) scoreB += 1;
      return scoreB - scoreA;
    })
    .slice(0, limit);
};
